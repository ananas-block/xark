//! `xark client` — generate a typed client from `schema.json`.
//!
//! `xark build` writes `target/xark/<name>/schema.json` from the `#[circuit]` fn's
//! parameter types (each one's `xark::Input::TYPE`), so a client comes straight from
//! build output: no `xark setup`, no proof.
//!
//! Generation has two halves:
//!
//! * [`model`]: `schema.json` resolved into the standard types (`Ty`): a date, a
//!   string, an enum choice or set, bytes, a number, a struct, … The same for every
//!   language. With the `#[input]` functions of the crate and its dependencies, built into `client.wasm`
//!   beside the circuit, so a client calls the crate's own Rust (constructors,
//!   helpers) instead of a hand-written copy.
//! * a target per language, saying how each standard type looks in it (its own
//!   types, and the JSON form the shared codec takes). [`ts`] is TypeScript; a
//!   Python or Go client is one more target over the same model.
//!
//! No target encodes field elements itself: values go to xark-wasm (or, for another
//! language, the same Rust codec through its bindings), which encodes them against
//! the schema exactly as `xark prove --inputs` does (`xark_schema`).

pub mod model;
pub mod ts;

use std::path::PathBuf;

use anyhow::{Context, Result};
use clap::{Args, ValueEnum};
use serde_json::Value;

use crate::xark_project::XarkProject;

#[derive(Args, Debug)]
pub struct ClientArgs {
    /// Circuit crate directory (or its `target/xark/` output dir). Defaults to the
    /// current directory.
    #[arg(value_hint = clap::ValueHint::DirPath)]
    pub path: Option<PathBuf>,
    /// Client language.
    #[arg(long, value_enum, default_value_t = Lang::Ts)]
    pub lang: Lang,
    /// Output file. Defaults to `target/xark/<name>/<circuit>.<ext>`.
    #[arg(long, short, value_hint = clap::ValueHint::FilePath)]
    pub out: Option<PathBuf>,
    /// Skip the Rust client functions (`#[input]` on an `impl`, built as
    /// `client.wasm`): for a crate whose host code doesn't build for wasm.
    #[arg(long)]
    pub no_functions: bool,
}

#[derive(ValueEnum, Clone, Copy, Debug)]
pub enum Lang {
    /// TypeScript.
    Ts,
}

impl Lang {
    fn name(self) -> &'static str {
        match self {
            Lang::Ts => "TypeScript",
        }
    }
    fn ext(self) -> &'static str {
        match self {
            Lang::Ts => "ts",
        }
    }
    /// The client, importing the schema from `schema_file` (a sibling's name).
    fn generate(self, m: &model::Model, schema_file: &str) -> Result<String> {
        match self {
            Lang::Ts => ts::generate(m, schema_file),
        }
    }
}

/// The crate a `target/xark/<name>/` directory belongs to.
fn crate_dir(xark_dir: &std::path::Path) -> Option<PathBuf> {
    let target = xark_dir.parent()?.parent()?;
    (target.file_name()? == "target").then(|| target.parent().map(PathBuf::from))?
}

/// On the first line of every generated client.
pub const MARKER: &str = "Generated by `xark client`";

pub fn run(args: ClientArgs) -> Result<()> {
    let project = XarkProject::resolve(args.path.clone())?;
    let schema_path = project.xark_dir.join("schema.json");
    let text = std::fs::read_to_string(&schema_path).map_err(|_| {
        anyhow::anyhow!(
            "no schema at {} — run `xark build {}` first (no setup or proof needed)",
            schema_path.display(),
            super::path_arg(&args.path)
        )
    })?;
    let schema: Value = serde_json::from_str(&text)
        .with_context(|| format!("reading {}", schema_path.display()))?;
    let mut model = model::Model::new(&schema)?;
    // Client functions (`#[input]` on an `impl`, in this crate or any it uses): build
    // the crate's host code as `client.wasm` beside the circuit, and type its
    // functions from the module's descriptions.
    if let Some(krate) = crate_dir(&project.xark_dir).filter(|_| !args.no_functions) {
        let path = project.xark_dir.join("client.wasm");
        match xark_frontend::build_client(&krate, &krate.join("target/xark-client")) {
            Ok(wasm) => {
                let lines = xark_frontend::custom_section(&wasm, "xark.exports");
                let skipped = model.add_exports(&schema, &String::from_utf8_lossy(&lines))?;
                for s in skipped {
                    eprintln!(
                        "{} skipping `{s}`: it uses a type this circuit's inputs don't",
                        crate::style::tag()
                    );
                }
                for e in model.exports.iter().filter(|e| model.shares_field_name(e)) {
                    eprintln!(
                        "{} `{t}::{n}` has a field's name, so it can't be a method on a `{t}` \
                         in the client (only `{t}.{n}(value, …)`): rename it to chain it",
                        crate::style::warn("warning:"),
                        t = e.ty,
                        n = e.name,
                    );
                }
                if model.exports.is_empty() {
                    let _ = std::fs::remove_file(&path);
                } else {
                    std::fs::write(&path, &wasm)
                        .with_context(|| format!("writing {}", path.display()))?;
                }
            }
            Err(e) => {
                let _ = std::fs::remove_file(&path);
                // A client without the crate's Rust functions would only fail later, where
                // they're called: stop here, with cargo's errors above.
                anyhow::bail!(
                    "the crate's Rust client functions (client.wasm, its host code built for \
                     wasm) don't build: {e} (the errors are above). Fix them, or pass \
                     `--no-functions` for a client without them."
                );
            }
        }
    }
    let out = args.out.unwrap_or_else(|| {
        project
            .xark_dir
            .join(format!("{}.{}", model.circuit, args.lang.ext()))
    });
    if let Some(dir) = out.parent().filter(|d| !d.as_os_str().is_empty()) {
        std::fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
    }
    // The schema beside the client (`zk_kyc.schema.json`), which the client imports:
    // written together, so the two always agree.
    let stem = out
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or(&model.circuit);
    let schema_file = format!("{stem}.schema.json");
    let schema_out = out.with_file_name(&schema_file);
    std::fs::write(&schema_out, serde_json::to_string_pretty(&schema)? + "\n")
        .with_context(|| format!("writing {}", schema_out.display()))?;
    std::fs::write(&out, args.lang.generate(&model, &schema_file)?)
        .with_context(|| format!("writing {}", out.display()))?;
    println!(
        "{}",
        crate::style::brand(&format!(
            "✅ {} client for `{}` at {}",
            args.lang.name(),
            model.circuit,
            out.display()
        ))
    );
    // What using it takes: the runtime it imports (this release's), the settings its
    // schema import needs, and where to start.
    let full = env!("CARGO_PKG_VERSION");
    let release = full.rsplit_once('.').map_or(full, |(mm, _)| mm);
    let name = ts::pascal(&model.circuit);
    eprintln!(
        "{}",
        crate::style::next_steps(&[
            (
                format!("npm install @blueshift-gg/xark-wasm@{release}"),
                "the runtime the client imports",
            ),
            (
                "tsconfig: \"resolveJsonModule\": true".to_string(),
                "it imports its schema; `module` esnext, nodenext or preserve",
            ),
            (
                format!(
                    "await {name}.prover(\"<url of target/xark/{}/>\")",
                    model.circuit
                ),
                "then .prove(inputs); `.verifier(…)` to verify",
            ),
        ])
    );
    Ok(())
}
