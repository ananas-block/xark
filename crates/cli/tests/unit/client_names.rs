/// `clients/check` also runs this test with an output directory, then invokes
/// strict tsc on these actual generated clients and their usage assertions.
#[test]
fn allocates_collision_free_client_names() {
    let output = std::env::var_os("XARK_CLIENT_NAMES_OUT").map(std::path::PathBuf::from);
    for (circuit, (schema, usage)) in [
        ("escrow", program_fixture("escrow")),
        ("withdraw", program_fixture("withdraw")),
        ("clash", all_names_fixture()),
    ] {
        let mut model = Model::new(&schema).unwrap();
        if circuit == "clash" {
            model.add_exports(&schema, r#"{"export":"ClashPublicInputs.copy","type":"ClashPublicInputs","name":"copy","self":"ref","params":[],"returns":"ClashPublicInputs","doc":""}
{"export":"ClashPublicInputs.from","type":"ClashPublicInputs","name":"from","self":null,"params":[{"name":"value","type":"ClashPublicInputs"}],"returns":"ClashPublicInputs","doc":""}
{"export":"Default.copy","type":"Default","name":"copy","self":"ref","params":[],"returns":"Default","doc":""}
{"export":"Default.fooBar","type":"Default","name":"fooBar","self":"ref","params":[],"returns":"Field","doc":""}
{"export":"Default.constructor","type":"Default","name":"constructor","self":"ref","params":[],"returns":"Default","doc":""}
{"export":"Default.toJSON","type":"Default","name":"toJSON","self":"ref","params":[],"returns":"Default","doc":""}"#).unwrap();
        } else {
            let owner = format!("{}PublicInputs", pascal(circuit));
            let receiver = format!("{circuit}publicinputsstruct");
            let export = serde_json::json!({
                "export": format!("{owner}.copy"), "type": owner, "name": "copy", "self": "ref",
                "params": [
                    {"name": receiver, "type": owner},
                    {"name": format!("{receiver}Self"), "type": owner},
                    {"name": "same_name", "type": "Field"},
                    {"name": "sameName", "type": "Field"},
                    {"name": "sameNameParam", "type": "Field"},
                    {"name": "Field", "type": "Field"},
                    {"name": format!("decode{owner}Struct"), "type": "Field"}
                ],
                "returns": owner, "doc": ""
            });
            model.add_exports(&schema, &export.to_string()).unwrap();
        }
        let stem = format!("{circuit}.schema");
        let generated = generate(&model, &stem).unwrap();
        assert_eq!(generated, generate(&model, &stem).unwrap());
        let mut declared = BTreeSet::new();
        for line in generated.lines() {
            let mut words = line.split_whitespace();
            if words.next() == Some("export")
                && matches!(words.next(), Some("interface" | "class" | "type"))
            {
                let identifier = words.next().unwrap();
                assert!(
                    declared.insert(identifier),
                    "duplicate type {identifier} in {circuit}"
                );
            }
        }
        if circuit == "clash" {
            assert!(generated.contains("export interface ClashInputsStruct {"));
            assert!(generated.contains("export interface ClashPublicInputsStruct2 {"));
            assert!(generated.contains("function decodePublicValue("));
            assert!(generated.contains("function decodeFooValue2("));
            assert!(generated.contains("export interface FooValueDecoded {"));
            assert!(generated.contains("ClashPublicInputs: ClashPublicInputsStruct2;"));
            assert!(
                generated.contains(
                    ".call<Json<ClashPublicInputsStruct2Value>>(\"ClashPublicInputs.copy\""
                )
            );
            assert!(generated.contains("copy(defaultSelf: Default)"));
            assert!(!generated.contains("  constructor(): DefaultValue"));
            assert!(!generated.contains("  fooBar(): Field"));
            assert!(!generated.contains("  toJSON(): DefaultValue"));
        } else {
            let name = pascal(circuit);
            assert!(generated.contains(&format!("export interface {name}PublicInputsStruct {{")));
            assert!(generated.contains(&format!("public: {name}PublicInputsStruct;")));
            assert!(generated.contains(&format!(
                "export interface {name}PublicInputs {{\n  publicHash: FieldInput;\n}}"
            )));
            let receiver = format!("{circuit}publicinputsstruct");
            assert!(generated.contains(&format!(
                    "\"{name}PublicInputs.copy\", [{receiver}Self2, {receiver}, {receiver}Self, sameName, sameNameParam2, sameNameParam, FieldParam, decode{name}PublicInputsStructParam]"
                )));
        }
        if let Some(output) = &output {
            std::fs::create_dir_all(output).unwrap();
            std::fs::write(output.join(format!("{circuit}.ts")), generated).unwrap();
            std::fs::write(
                output.join(format!("{stem}.ts")),
                schema_module(circuit, &schema).unwrap(),
            )
            .unwrap();
            std::fs::write(output.join(format!("{circuit}.usage.ts")), usage).unwrap();
        }
    }
}
