#!/usr/bin/env python3
"""Regenerate Makefile.publish: every publishable crate, dependencies first.

    scripts/gen-publish-makefile.py           # rewrite Makefile.publish
    scripts/gen-publish-makefile.py --check   # fail if it is out of date

Reads `cargo metadata` for the root workspace and for `crates/lang` (its own
workspace). A crate is publishable unless its manifest says `publish = false`.
Every dependency of a publishable crate on another local crate (dev-dependencies
included, since crates.io must resolve them too) must itself be publishable and
carry a `version`; anything else is an error here rather than halfway through a
real publish.
"""
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Makefile.publish")
SEPARATE = {"crates/lang"}  # own workspace: published with `cd <dir> && cargo publish`


def metadata(manifest_dir):
    out = subprocess.check_output(
        ["cargo", "metadata", "--no-deps", "--format-version", "1"],
        cwd=os.path.join(ROOT, manifest_dir),
    )
    return json.loads(out)["packages"]


def main():
    pkgs = {}
    for d in [".", *sorted(SEPARATE)]:
        for p in metadata(d):
            if p["manifest_path"].startswith(ROOT):
                pkgs[p["name"]] = p
    version = pkgs["xark-cli"]["version"]
    publishable = {n for n, p in pkgs.items() if p["publish"] != []}
    errors, deps = [], {}
    for n in sorted(publishable):
        deps[n] = set()
        for d in pkgs[n]["dependencies"]:
            if d["name"] not in pkgs or d.get("path") is None:
                continue
            if d["kind"] == "dev" and d["req"] == "*":
                continue  # path-only dev-dependency: cargo strips it on publish
            if d["req"] == "*":
                errors.append(f"{n} -> {d['name']}: path dependency without a version")
            if d["name"] not in publishable:
                errors.append(f"{n} -> {d['name']}: depends on an unpublished crate")
            if d["name"] != n:
                deps[n].add(d["name"])
    if errors:
        sys.exit("cannot publish:\n  " + "\n  ".join(errors))
    order, done = [], set()
    while len(order) < len(deps):
        ready = sorted(n for n in deps if n not in done and deps[n] <= done)
        if not ready:
            sys.exit("dependency cycle among: " + " ".join(sorted(set(deps) - done)))
        order += ready
        done |= set(ready)

    def cmd(n, dry):
        rel = os.path.relpath(os.path.dirname(pkgs[n]["manifest_path"]), ROOT)
        flag = " --dry-run" if dry else ""
        if rel in SEPARATE:
            return f"(cd {rel} && cargo publish{flag})"
        return f"cargo publish{flag} -p {n}"

    lines = [
        f"# Generated by scripts/gen-publish-makefile.py for xark (v{version}) — don't edit.",
        "# Publishes every crate to crates.io in dependency order (leaves first).",
        "# `cargo publish` waits for each crate to index before the next, so deps",
        "# are always available when a dependent is published.",
        "#",
        "# Usage:",
        "#   make -f Makefile.publish publish-dry   # verify everything, upload nothing",
        "#   make -f Makefile.publish publish       # real publish (needs `cargo login`)",
        "",
        ".PHONY: publish publish-dry $(addprefix pub-,$(PKGS))",
        "",
        "PKGS := " + " ".join(order),
        "",
        "publish:",
    ]
    for n in order:
        lines += [f'\t@echo ">>> publishing {n}"', "\t" + cmd(n, False)]
    lines += ['\t@echo "All crates published."', "", "publish-dry:"]
    for n in order:
        lines += [f'\t@echo ">>> dry-run {n}"', "\t" + cmd(n, True)]
    lines += ['\t@echo "Dry-run complete — all crates package cleanly."']
    text = "\n".join(lines) + "\n"
    if "--check" in sys.argv:
        if open(OUT).read() != text:
            sys.exit("Makefile.publish is out of date: run scripts/gen-publish-makefile.py")
        print(f"Makefile.publish is up to date ({len(order)} crates)")
    else:
        open(OUT, "w").write(text)
        print(f"wrote Makefile.publish ({len(order)} crates)")


main()
